// Builds service-area-zips.js: every ZIP whose center is within RADIUS_MI (straight line) of
// Edwardsville, from the Census ZCTA Gazetteer (public domain). Re-run if Dan changes his range:
//   node tools/area-zips.js path/to/2025_Gaz_zcta_national.txt [radiusMiles]
// Source: https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip
const fs = require('fs');
const path = require('path');

const CENTER = { lat: 38.8114, lng: -89.9532 }; // Edwardsville, IL (same point as the site's schema)
// ZIPs Dan does not service even though they're in range. The schedulers tell these visitors plainly
// and don't send the booking. East St. Louis / Alorton / Centreville / Cahokia Heights:
const EXCLUDED = ['62201', '62203', '62204', '62205', '62206', '62207'];
const [file, radiusArg] = process.argv.slice(2);
const RADIUS_MI = Number(radiusArg) || 20;
if (!file) { console.error('Usage: node tools/area-zips.js <gazetteer.txt> [radiusMiles]'); process.exit(1); }

const toRad = d => d * Math.PI / 180;
const miles = (a, b) => {
  const dLat = toRad(b.lat - a.lat), dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 3958.8 * 2 * Math.asin(Math.sqrt(h));
};

const rows = fs.readFileSync(file, 'utf8').trim().split('\n');
const head = rows.shift().split('|').map(s => s.trim());
const iZip = head.indexOf('GEOID'), iLat = head.indexOf('INTPTLAT'), iLng = head.indexOf('INTPTLONG');
const inRange = rows.map(r => r.split('|'))
  .map(c => ({ zip: c[iZip], d: miles(CENTER, { lat: +c[iLat], lng: +c[iLng] }) }))
  .filter(z => z.d <= RADIUS_MI && !EXCLUDED.includes(z.zip))
  .sort((a, b) => a.zip.localeCompare(b.zip));

const out = `// Generated by tools/area-zips.js: ZIPs within ${RADIUS_MI} mi (straight line) of Edwardsville, IL.
// ${inRange.length} ZIPs (after removing ${EXCLUDED.length} not serviced), Census ZCTA Gazetteer. Do not edit by hand; re-run the script.
window.DMAK_AREA = { radiusMi: ${RADIUS_MI}, excluded: ${JSON.stringify(EXCLUDED)}, zips: ${JSON.stringify(inRange.map(z => z.zip))} };
`;
fs.writeFileSync(path.join(__dirname, '..', 'service-area-zips.js'), out);
console.log(`${inRange.length} ZIPs within ${RADIUS_MI} mi`);
console.log(inRange.map(z => `${z.zip} ${z.d.toFixed(1)}mi`).join('\n'));
